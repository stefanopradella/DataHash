function outputFile = buildDataHash(outputFile)
    %buildDataHash - Assemble the standalone DataHash distribution file
    %   outputFile = buildDataHash() writes build/DataHash.m
    %   and returns its absolute path as a character vector. The file contains
    %   the authored functions under src. Distribute it with license.txt.
    %
    %   outputFile = buildDataHash(outputFile) writes to another location.
    %   Specify a character vector or scalar string ending in DataHash.m.
    %   The parent folder must exist and the destination must be outside src.
    %   An existing file is replaced only after writing and closing the
    %   complete new file successfully. Identical sources produce identical
    %   UTF-8 output with LF line endings.
    %
    %   See also DataHash, fileread

    % Copyright (c) 2026, Stefano Pradella. See license.txt.

    arguments
        outputFile {mustBeOutputFile} = ...
            fullfile(fileparts(mfilename('fullpath')), 'build', 'DataHash.m')
    end

    repositoryFolder = fileparts(mfilename('fullpath'));
    sourceFolder = fullfile(repositoryFolder, 'src');
    outputFile = char(outputFile);
    [outputFolder, outputName, outputExtension] = fileparts(outputFile);
    if ~strcmp([outputName, outputExtension], 'DataHash.m')
        error('buildDataHash:InvalidOutputName', ...
            'The output file must be named DataHash.m.');
    end
    if isempty(outputFolder)
        outputFolder = pwd;
    end
    if nargin == 0 && ~isfolder(outputFolder)
        mkdir(outputFolder);
    end
    [status, folderInfo] = fileattrib(outputFolder);
    if ~status || ~isscalar(folderInfo) || ~folderInfo.directory
        error('buildDataHash:MissingOutputFolder', ...
            'The output folder must exist: %s', outputFolder);
    end
    outputFolder = folderInfo.Name;
    outputFile = fullfile(outputFolder, 'DataHash.m');
    if startsWith([outputFolder, filesep], ...
            [sourceFolder, filesep], 'IgnoreCase', ispc)
        error('buildDataHash:SourceDestination', ...
            'The output file must be outside the authored source folder.');
    end
    if isfolder(outputFile)
        error('buildDataHash:InvalidOutputFile', ...
            'The output path names a folder: %s', outputFile);
    end

    sourceFiles = {
        'DataHash.m'
        'getHashFunctions.m'
        'hasDataHashCore.m'
        'digestNumericArray.m'
        'digestFile.m'
        'nativeDigestCore.m'
        'serializeObject.m'
        'md2/md2Digest.m'
        'md2/md2DigestFile.m'
        'md2/md2Initialize.m'
        'md2/md2Compress.m'
        'md2/md2Finalize.m'
        'md5/md5Digest.m'
        'md5/md5DigestFile.m'
        'md5/md5Initialize.m'
        'md5/md5Compress.m'
        'md5/md5Finalize.m'
        'sha1/sha1Digest.m'
        'sha1/sha1DigestFile.m'
        'sha1/sha1Initialize.m'
        'sha1/sha1Compress.m'
        'sha1/sha1Finalize.m'
        'sha256/sha256Digest.m'
        'sha256/sha256DigestFile.m'
        'sha256/sha256Initialize.m'
        'sha256/sha256Compress.m'
        'sha256/sha256Finalize.m'
        'sha384/sha384Digest.m'
        'sha384/sha384DigestFile.m'
        'sha384/sha384Initialize.m'
        'sha512/sha512Digest.m'
        'sha512/sha512DigestFile.m'
        'sha512/sha512Initialize.m'
        'sha512/sha512Compress.m'
        'sha512/sha512Finalize.m'
    };
    expectedFiles = cellfun(@(file) fullfile(sourceFolder, file), ...
        sourceFiles, 'UniformOutput', false);
    actualFiles = dir(fullfile(sourceFolder, '**', '*.m'));
    actualFiles = arrayfun(@(file) fullfile(file.folder, file.name), ...
        actualFiles, 'UniformOutput', false);
    missingFiles = setdiff(expectedFiles, actualFiles);
    unlistedFiles = setdiff(actualFiles, expectedFiles);
    if ~isempty(missingFiles) || ~isempty(unlistedFiles)
        error('buildDataHash:SourceListMismatch', ...
            'Update the source list to match src. Missing: %s. Unlisted: %s.', ...
            strjoin(missingFiles, ', '), strjoin(unlistedFiles, ', '));
    end

    sections = cell(numel(sourceFiles) + 1, 1);
    sections{1} = readText(expectedFiles{1});
    sections{2} = sprintf(['%% Generated by buildDataHash.m from src/DataHash.m', ...
        ' and the sources below.\n', ...
        '%% Edit the authored files under src, then rebuild this file.\n', ...
        '%% Copyright (c) 2018-2019, Jan Simon\n', ...
        '%% Portions copyright (c) 2026, Stefano Pradella. See license.txt.\n']);
    for fileIndex = 2:numel(sourceFiles)
        sections{fileIndex + 1} = sprintf('%% Source: src/%s\n%s\n', ...
            sourceFiles{fileIndex}, readText(expectedFiles{fileIndex}));
    end
    bytes = unicode2native(strjoin(sections, newline), 'UTF-8');

    % Keep the temporary file beside the destination for the final rename.
    temporaryFile = [tempname(outputFolder), '.m'];
    [fileId, message] = fopen(temporaryFile, 'wb');
    if fileId == -1
        error('buildDataHash:OpenFailed', ...
            'Cannot create the output file: %s', message);
    end
    cleanup = onCleanup(@() cleanupTemporaryFile(temporaryFile, fileId));
    if fwrite(fileId, bytes, 'uint8') ~= numel(bytes)
        error('buildDataHash:WriteFailed', ...
            'Could not write the complete output file: %s', temporaryFile);
    end
    closeStatus = fclose(fileId);
    if closeStatus ~= 0
        error('buildDataHash:CloseFailed', ...
            'Could not close the output file: %s', temporaryFile);
    end
    [status, message] = movefile(temporaryFile, outputFile, 'f');
    if ~status
        error('buildDataHash:ReplaceFailed', ...
            'Cannot replace the output file: %s', message);
    end
end

function mustBeOutputFile(outputFile)
    if ~((ischar(outputFile) && isrow(outputFile) && ~isempty(outputFile)) || ...
            (isstring(outputFile) && isscalar(outputFile) && ...
            ~ismissing(outputFile) && strlength(outputFile) > 0))
        error('buildDataHash:InvalidOutputFile', ...
            'Specify a nonempty character vector or scalar string.');
    end
end

function text = readText(fileName)
    text = fileread(fileName);
    text = regexprep(text, '\r\n?', '\n');
    text = regexprep(text, '\n*$', '');
end

function cleanupTemporaryFile(fileName, fileId)
    if ~isempty(fopen(fileId))
        fclose(fileId);
    end
    if isfile(fileName)
        delete(fileName);
    end
end
