classdef DataHashLegacyCompatibilityTest < matlab.unittest.TestCase
    % Frozen results from the Java-backed DataHash implementation.

    properties (TestParameter)
        digestCase = digestCases()
        boundaryCase = boundaryCases()
        arrayCase = arrayCases()
    end

    methods (TestClassSetup)
        function addSourceFolder(testCase)
            repositoryFolder = fileparts(fileparts(mfilename('fullpath')));
            sourceFolder = fullfile(repositoryFolder, 'src');
            originalPath = path;
            testCase.addTeardown(@path, originalPath);
            addpath(sourceFolder, ...
                fullfile(sourceFolder, 'md2'), ...
                fullfile(sourceFolder, 'md5'), ...
                fullfile(sourceFolder, 'sha1'), ...
                fullfile(sourceFolder, 'sha256'), ...
                fullfile(sourceFolder, 'sha384'), ...
                fullfile(sourceFolder, 'sha512'));
        end
    end

    methods (Test)
        function digestCompatibility(testCase, digestCase)
            actual = DataHash(digestCase.data, digestCase.method, 'bin');
            testCase.verifyEqual(actual, digestCase.expected, ...
                digestCase.label);
        end

        function digestBlockBoundaries(testCase, boundaryCase)
            data = uint8(0:(boundaryCase.length - 1));
            actual = DataHash(data, boundaryCase.method, 'bin');
            testCase.verifyEqual(actual, boundaryCase.expected, ...
                boundaryCase.label);
        end

        function arraySerializationCompatibility(testCase, arrayCase)
            actual = DataHash(arrayCase.data, 'MD5', 'array');
            testCase.verifyEqual(actual, arrayCase.expected, ...
                arrayCase.label);
        end
    end
end

