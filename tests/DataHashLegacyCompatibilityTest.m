function namedCases = nameCases(cases, fieldNames)
% Convert a table-like cell array into named TestParameter structures.

    namedCases = struct;
    for caseIndex = 1:size(cases, 1)
        item = struct;
        for fieldIndex = 1:numel(fieldNames)
            item.(fieldNames{fieldIndex}) = cases{caseIndex, fieldIndex + 1};
        end
        namedCases.(cases{caseIndex, 1}) = item;
    end
end
