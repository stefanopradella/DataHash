classdef DataHashTest < matlab.unittest.TestCase
    % Evolving regression coverage for the current DataHash interface.
    % Add new features and regressions here; preserve the historical suite.
    % Copyright (c) 2026, Stefano Pradella. See ../license.txt.

    properties (TestParameter)
        digestCase = digestCases()
        boundaryCase = boundaryCases()
        arrayCase = arrayCases()
        outputCase = outputCases()
        base64Case = base64Cases()
        defaultCase = defaultCases()
        optionCase = optionCases()
        optionRepresentation = struct('characterVector', @char, 'scalarString', @string)
        invalidOptionCase = invalidOptionCases()
        invalidBinaryData = invalidBinaryInputs()
        invalidAsciiData = invalidAsciiInputs()
        invalidArgumentCase = invalidArgumentCases()
        emptyBinaryData = emptyBinaryInputs()
        method = {'MD2', 'MD5', 'SHA-1', 'SHA-256', 'SHA-384', 'SHA-512'}
    end

    methods (TestClassSetup)
        function addSourceFolder(testCase)
            repositoryFolder = fileparts(fileparts(mfilename('fullpath')));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(repositoryFolder, 'src'), 'IncludingSubfolders', true));
        end
    end

    methods (Test)
        function digestCompatibility(testCase, digestCase)
            actual = DataHash(digestCase.data, digestCase.method, 'bin');
            testCase.verifyEqual(actual, digestCase.expected, digestCase.label);
        end

        function digestBlockBoundaries(testCase, boundaryCase)
            data = uint8(0:(boundaryCase.length - 1));
            actual = DataHash(data, boundaryCase.method, 'bin');
            testCase.verifyEqual(actual, boundaryCase.expected, boundaryCase.label);
        end

        function arraySerializationCompatibility(testCase, arrayCase)
            actual = DataHash(arrayCase.data, 'MD5', 'array');
            testCase.verifyEqual(actual, arrayCase.expected, arrayCase.label);
        end

        function fileDigestCompatibility(testCase, digestCase)
            fileName = testCase.writeTemporaryFile(digestCase.data);
            actual = DataHash(fileName, digestCase.method, 'file');
            testCase.verifyEqual(actual, digestCase.expected, digestCase.label);
        end

        function fileDigestBlockBoundaries(testCase, boundaryCase)
            data = uint8(0:(boundaryCase.length - 1));
            fileName = testCase.writeTemporaryFile(data);
            actual = DataHash(fileName, boundaryCase.method, 'file');
            testCase.verifyEqual(actual, boundaryCase.expected, boundaryCase.label);
        end

        function outputKnownAnswer(testCase, outputCase)
            actual = DataHash(outputCase.data, outputCase.options{:});
            testCase.verifyEqual(actual, outputCase.expected);
        end

        function base64Padding(testCase, base64Case)
            padded = DataHash('abc', base64Case.method, 'ascii', 'base64');
            short = DataHash('abc', base64Case.method, 'ascii', 'short');

            testCase.verifyEqual(padded, base64Case.expected);
            testCase.verifyEqual(short, strrep(base64Case.expected, '=', ''));
        end

        function versionInformation(testCase)
            info = DataHash();
            testCase.verifyClass(info, 'struct');
            testCase.verifySize(info, [1, 1]);
            testCase.verifyEqual(info.HashVersion, 5);
            testCase.verifySize(info.Date, [1, 3]);
            testCase.verifyEqual(info.HashMethod, ...
                {'MD2', 'MD5', 'SHA-1', 'SHA-256', 'SHA-384', 'SHA-512'});
        end

        function trailingDefaults(testCase, defaultCase)
            data = uint8('abc');
            actual = DataHash(data, defaultCase.options{:});
            explicit = DataHash(data, defaultCase.explicitOptions{:});
            testCase.verifyEqual(actual, explicit);
        end

        function optionText(testCase, optionCase, optionRepresentation)
            options = cellfun(optionRepresentation, optionCase.options, ...
                'UniformOutput', false);
            actual = DataHash(optionCase.data, options{:});
            testCase.verifyEqual(actual, optionCase.expected);
        end

        function invalidOptions(testCase, invalidOptionCase)
            testCase.verifyError(@() DataHash([], invalidOptionCase{:}), ...
                'DataHash:InvalidOption');
        end

        function invalidBinaryInput(testCase, invalidBinaryData)
            testCase.verifyError(@() DataHash(invalidBinaryData, 'MD5', 'bin'), ...
                'DataHash:InvalidBinaryData');
        end

        function invalidAsciiInput(testCase, invalidAsciiData)
            testCase.verifyError(@() DataHash(invalidAsciiData, 'MD5', 'ascii'), ...
                'DataHash:InvalidAsciiData');
        end

        function invalidArgument(testCase, invalidArgumentCase)
            % MATLAB validation identifiers vary with release and input type.
            testCase.verifyThat(@() DataHash([], invalidArgumentCase{:}), ...
                matlab.unittest.constraints.Throws(?MException));
        end

        function missingFile(testCase, method)
            fileName = tempname;
            testCase.verifyError(@() DataHash(fileName, method, 'file'), ...
                'DataHash:FileOpen');
        end

        function emptyBinaryInput(testCase, emptyBinaryData)
            actual = DataHash(emptyBinaryData, 'MD5', 'bin');
            testCase.verifyEqual(actual, 'd41d8cd98f00b204e9800998ecf8427e');
        end

        function arrayShapeAffectsHash(testCase)
            rowHash = DataHash(uint8([1, 2]), 'MD5', 'array');
            columnHash = DataHash(uint8([1; 2]), 'MD5', 'array');
            testCase.verifyNotEqual(rowHash, columnHash);
        end

        function structFieldOrder(testCase)
            data = struct('alpha', uint8([0, 128, 255]), ...
                'beta', {{int16(-2), 'abc'}});
            reordered = orderfields(data, {'beta', 'alpha'});
            actual = DataHash(reordered);

            testCase.verifyEqual(actual, '212431b3a94255574d203754138d6299');
        end
    end

    methods (Access = private)
        function fileName = writeTemporaryFile(testCase, data)
            folder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            fileName = fullfile(folder.Folder, 'input.bin');
            [fileId, message] = fopen(fileName, 'wb');
            testCase.assertNotEqual(fileId, -1, message);
            fileGuard = onCleanup(@() fclose(fileId));
            count = fwrite(fileId, data, 'uint8');
            testCase.assertEqual(count, numel(data));
            clear fileGuard;
        end
    end
end

