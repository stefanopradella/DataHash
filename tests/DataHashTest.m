    methods (Test, TestTags = {'FileStreaming'})
        function fileStreamingBoundaries(testCase, streamingCase)
            byteIndex = 0:(streamingCase.length - 1);
            % This pattern gives consecutive 1 MiB chunks different contents.
            data = uint8(mod(37 * byteIndex + floor(byteIndex / 251) + 17, 256));
            fileName = testCase.writeTemporaryFile(data);
            originalFiles = testCase.trackOpenFiles();

            fileHash = DataHash(fileName, streamingCase.method, 'file');
            testCase.verifyEqual(openFiles(), originalFiles);
            memoryHash = DataHash(data, streamingCase.method, 'bin');

            testCase.verifyEqual(fileHash, streamingCase.expected, streamingCase.label);
            testCase.verifyEqual(memoryHash, streamingCase.expected, streamingCase.label);
            testCase.verifyEqual(fileHash, memoryHash, streamingCase.label);
        end
    end

    methods (Access = private)
        function installCpuDispatchProbe(testCase, outputName)
            arguments
                testCase
                outputName (1, 1) string = "DataHashCpuDispatchProbe"
            end
            testCase.assumeNotEmpty(mex.getCompilerConfigurations('C', 'Selected'), ...
                'A configured C compiler is required for CPU-dispatch checks.');
            repositoryFolder = fileparts(fileparts(mfilename('fullpath')));
            folder = testCase.applyFixture( ...
                matlab.unittest.fixtures.TemporaryFolderFixture);
            contents = strjoin({ ...
                '/* Emulate CPUID/XCR0 while compiling the actual MEX core and its ISA paths.', ...
                ' * One-input calls return features, XGETBV calls, and reported SHA/AVX2 flags', ...
                ' * for each column', ...
                ' * of [maximum leaf; leaf-1 ECX; leaf-7 EBX; XCR0 low; XCR0 high].', ...
                ' * Normal core calls emulate a CPU without extensions, retaining all compiled', ...
                ' * instruction paths so the runtime scalar fallback can be checked.', ...
                ' * Copyright (c) 2026, Stefano Pradella. See ../../license.txt. */', ...
                '', ...
                '#include "mex.h"', ...
                '#include <stdint.h>', ...
                '#include <string.h>', ...
                '', ...
                'static unsigned int simulatedCpu[5];', ...
                'static unsigned int xgetbvCalls;', ...
                '', ...
                'static void simulatedCpuId(unsigned int leaf, unsigned int subleaf,', ...
                '    unsigned int values[4])', ...
                '{', ...
                '    memset(values, 0, 4 * sizeof(*values));', ...
                '    if (subleaf != 0 || leaf > simulatedCpu[0]) {', ...
                '        mexErrMsgIdAndTxt("DataHashCpuDispatchProbe:CpuId", "Unsupported CPUID leaf queried.");', ...
                '    }', ...
                '    if (leaf == 0) {', ...
                '        values[0] = simulatedCpu[0];', ...
                '    } else if (leaf == 1) {', ...
                '        values[2] = simulatedCpu[1];', ...
                '    } else if (leaf == 7) {', ...
                '        values[1] = simulatedCpu[2];', ...
                '    }', ...
                '}', ...
                '', ...
                'static uint64_t simulatedXgetbv(unsigned int index)', ...
                '{', ...
                '    if (index != 0 || (simulatedCpu[1] & 0x0c000000u) != 0x0c000000u) {', ...
                '        mexErrMsgIdAndTxt("DataHashCpuDispatchProbe:Xgetbv", "XGETBV executed without OS support.");', ...
                '    }', ...
                '    ++xgetbvCalls;', ...
                '    return (uint64_t)simulatedCpu[3] | ((uint64_t)simulatedCpu[4] << 32);', ...
                '}', ...
                '', ...
                '#if defined(_M_X64) && defined(_MSC_VER) && _MSC_VER >= 1910', ...
                '#include <intrin.h>', ...
                '#include <immintrin.h>', ...
                '#define __cpuidex(values, leaf, subleaf) \', ...
                '    simulatedCpuId((unsigned int)(leaf), (unsigned int)(subleaf), (unsigned int *)(values))', ...
                '#define _xgetbv(index) simulatedXgetbv(index)', ...
                '#elif defined(__x86_64__) && defined(__GNUC__)', ...
                '#include <cpuid.h>', ...
                '#include <immintrin.h>', ...
                '#undef __cpuid_count', ...
                '#define __cpuid_count(leaf, subleaf, a, b, c, d) do { \', ...
                '    unsigned int simulatedValues[4]; \', ...
                '    simulatedCpuId(leaf, subleaf, simulatedValues); \', ...
                '    (a) = simulatedValues[0]; (b) = simulatedValues[1]; \', ...
                '    (c) = simulatedValues[2]; (d) = simulatedValues[3]; \', ...
                '} while (0)', ...
                '#define _xgetbv(index) simulatedXgetbv(index)', ...
                '#endif', ...
                '', ...
                '#define mexFunction dataHashCoreMexFunction', ...
                '#include "DataHashCore.c"', ...
                '#undef mexFunction', ...
                '', ...
                'void mexFunction(int nlhs, mxArray *plhs[], int nrhs, const mxArray *prhs[])', ...
                '{', ...
                '    if (nrhs == 1) {', ...
                '        size_t columnIndex, columnCount;', ...
                '        const uint32_t *cases;', ...
                '        uint32_t *results;', ...
