function state = sha512Compress(state, blocks)
%SHA512COMPRESS Update a SHA-384 or SHA-512 state with 128-byte blocks.

    arguments
        state (8, 1) uint64
        blocks (128, :) uint8
    end

    persistent constantHigh constantLow
    if isempty(constantHigh)
        constantHex = [ ...
            '428a2f98d728ae22'; '7137449123ef65cd'; ...
            'b5c0fbcfec4d3b2f'; 'e9b5dba58189dbbc'; ...
            '3956c25bf348b538'; '59f111f1b605d019'; ...
            '923f82a4af194f9b'; 'ab1c5ed5da6d8118'; ...
            'd807aa98a3030242'; '12835b0145706fbe'; ...
            '243185be4ee4b28c'; '550c7dc3d5ffb4e2'; ...
            '72be5d74f27b896f'; '80deb1fe3b1696b1'; ...
            '9bdc06a725c71235'; 'c19bf174cf692694'; ...
            'e49b69c19ef14ad2'; 'efbe4786384f25e3'; ...
            '0fc19dc68b8cd5b5'; '240ca1cc77ac9c65'; ...
            '2de92c6f592b0275'; '4a7484aa6ea6e483'; ...
            '5cb0a9dcbd41fbd4'; '76f988da831153b5'; ...
            '983e5152ee66dfab'; 'a831c66d2db43210'; ...
            'b00327c898fb213f'; 'bf597fc7beef0ee4'; ...
            'c6e00bf33da88fc2'; 'd5a79147930aa725'; ...
            '06ca6351e003826f'; '142929670a0e6e70'; ...
            '27b70a8546d22ffc'; '2e1b21385c26c926'; ...
            '4d2c6dfc5ac42aed'; '53380d139d95b3df'; ...
            '650a73548baf63de'; '766a0abb3c77b2a8'; ...
            '81c2c92e47edaee6'; '92722c851482353b'; ...
            'a2bfe8a14cf10364'; 'a81a664bbc423001'; ...
            'c24b8b70d0f89791'; 'c76c51a30654be30'; ...
            'd192e819d6ef5218'; 'd69906245565a910'; ...
            'f40e35855771202a'; '106aa07032bbd1b8'; ...
            '19a4c116b8d2d0c8'; '1e376c085141ab53'; ...
            '2748774cdf8eeb99'; '34b0bcb5e19b48a8'; ...
            '391c0cb3c5c95a63'; '4ed8aa4ae3418acb'; ...
            '5b9cca4f7763e373'; '682e6ff3d6b2b8a3'; ...
            '748f82ee5defb2fc'; '78a5636f43172f60'; ...
            '84c87814a1f0ab72'; '8cc702081a6439ec'; ...
            '90befffa23631e28'; 'a4506cebde82bde9'; ...
            'bef9a3f7b2c67915'; 'c67178f2e372532b'; ...
            'ca273eceea26619c'; 'd186b8c721c0c207'; ...
            'eada7dd6cde0eb1e'; 'f57d4f7fee6ed178'; ...
            '06f067aa72176fba'; '0a637dc5a2c898a6'; ...
            '113f9804bef90dae'; '1b710b35131c471b'; ...
            '28db77f523047d84'; '32caab7b40c72493'; ...
            '3c9ebe0a15c9bebc'; '431d67c49c100d4c'; ...
            '4cc5d4becb3e42b6'; '597f299cfc657e2a'; ...
            '5fcb6fab3ad6faec'; '6c44198c4a475817'];
        constantHigh = hex2dec(constantHex(:, 1:8));
        constantLow = hex2dec(constantHex(:, 9:16));
    end

    persistent isLittleEndian
    if isempty(isLittleEndian)
        [~, ~, endianness] = computer;
        isLittleEndian = endianness == 'L';
    end

    % SHA message words are big-endian, independently of the host.
    messageWords = reshape(typecast(blocks(:), 'uint32'), 32, []);
    if isLittleEndian
        messageWords = swapbytes(messageWords);
    end

    % Split 64-bit words into uint32 halves for the hot path. Partial
    % sums stay below 2^35 and are exact in double. Carry from each
    % low sum enters the high sum before reduction modulo 2^32.
    % Eight unrolled rounds return the scalar registers to their roles.
    stateHigh = uint32(bitshift(state, -32));
    stateLow = uint32(bitand(state, uint64(4294967295)));
    aHigh = stateHigh(1);
    aLow = stateLow(1);
    bHigh = stateHigh(2);
    bLow = stateLow(2);
    cHigh = stateHigh(3);
    cLow = stateLow(3);
    dHigh = stateHigh(4);
    dLow = stateLow(4);
    eHigh = stateHigh(5);
    eLow = stateLow(5);
    fHigh = stateHigh(6);
    fLow = stateLow(6);
    gHigh = stateHigh(7);
    gLow = stateLow(7);
    hHigh = stateHigh(8);
    hLow = stateLow(8);
    % Bound the high/low schedule workspace to 640 KiB.
    for batchStart = 1:1024:size(messageWords, 2)
        batchEnd = min(batchStart + 1023, size(messageWords, 2));
        batchCount = batchEnd - batchStart + 1;
        wordsHigh = zeros(80, batchCount, 'uint32');
        wordsLow = zeros(80, batchCount, 'uint32');
        wordsHigh(1:16, :) = messageWords(1:2:32, batchStart:batchEnd);
        wordsLow(1:16, :) = messageWords(2:2:32, batchStart:batchEnd);
        for wordIndex = 17:80
            previousHigh = wordsHigh(wordIndex - 15, :);
            previousLow = wordsLow(wordIndex - 15, :);
            sigma0High = bitxor(bitxor( ...
                bitor(bitshift(previousHigh, -1), bitshift(previousLow, 31)), ...
                bitor(bitshift(previousHigh, -8), bitshift(previousLow, 24))), ...
                bitshift(previousHigh, -7));
            sigma0Low = bitxor(bitxor( ...
                bitor(bitshift(previousLow, -1), bitshift(previousHigh, 31)), ...
                bitor(bitshift(previousLow, -8), bitshift(previousHigh, 24))), ...
                bitor(bitshift(previousLow, -7), bitshift(previousHigh, 25)));
            previousHigh = wordsHigh(wordIndex - 2, :);
            previousLow = wordsLow(wordIndex - 2, :);
            sigma1High = bitxor(bitxor( ...
                bitor(bitshift(previousHigh, -19), bitshift(previousLow, 13)), ...
                bitor(bitshift(previousLow, -29), bitshift(previousHigh, 3))), ...
                bitshift(previousHigh, -6));
            sigma1Low = bitxor(bitxor( ...
                bitor(bitshift(previousLow, -19), bitshift(previousHigh, 13)), ...
                bitor(bitshift(previousHigh, -29), bitshift(previousLow, 3))), ...
                bitor(bitshift(previousLow, -6), bitshift(previousHigh, 26)));
            sumLow = double(wordsLow(wordIndex - 16, :)) + double(sigma0Low) + ...
                double(wordsLow(wordIndex - 7, :)) + double(sigma1Low);
            carry = fix(sumLow * 2^-32);
            wordsLow(wordIndex, :) = uint32(sumLow - 4294967296 * carry);
            sumValue = double(wordsHigh(wordIndex - 16, :)) + double(sigma0High) + ...
                double(wordsHigh(wordIndex - 7, :)) + double(sigma1High) + carry;
            wordsHigh(wordIndex, :) = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
        end

        for blockIndex = 1:batchCount
            startAHigh = aHigh;
            startALow = aLow;
            startBHigh = bHigh;
            startBLow = bLow;
            startCHigh = cHigh;
            startCLow = cLow;
            startDHigh = dHigh;
            startDLow = dLow;
            startEHigh = eHigh;
            startELow = eLow;
            startFHigh = fHigh;
            startFLow = fLow;
            startGHigh = gHigh;
            startGLow = gLow;
            startHHigh = hHigh;
            startHLow = hLow;
            for roundIndex = 1:8:80
