                gHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                cLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                cHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(gHigh, -14), bitshift(gLow, 18)), ...
                    bitor(bitshift(gHigh, -18), bitshift(gLow, 14))), ...
                    bitor(bitshift(gLow, -9), bitshift(gHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(gLow, -14), bitshift(gHigh, 18)), ...
                    bitor(bitshift(gLow, -18), bitshift(gHigh, 14))), ...
                    bitor(bitshift(gHigh, -9), bitshift(gLow, 23)));
                choiceHigh = bitxor(aHigh, bitand(gHigh, bitxor(hHigh, aHigh)));
                temporaryHigh = double(bHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex + 6) + double(wordsHigh(roundIndex + 6, blockIndex));
                choiceLow = bitxor(aLow, bitand(gLow, bitxor(hLow, aLow)));
                temporaryLow = double(bLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex + 6) + double(wordsLow(roundIndex + 6, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(cHigh, -28), bitshift(cLow, 4)), ...
                    bitor(bitshift(cLow, -2), bitshift(cHigh, 30))), ...
                    bitor(bitshift(cLow, -7), bitshift(cHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(cLow, -28), bitshift(cHigh, 4)), ...
                    bitor(bitshift(cHigh, -2), bitshift(cLow, 30))), ...
                    bitor(bitshift(cHigh, -7), bitshift(cLow, 25)));
                majorityHigh = bitxor(bitand(cHigh, dHigh), ...
                    bitand(eHigh, bitxor(cHigh, dHigh)));
                majorityLow = bitxor(bitand(cLow, dLow), ...
                    bitand(eLow, bitxor(cLow, dLow)));
                sumLow = temporaryLow + double(fLow);
                carry = fix(sumLow * 2^-32);
                fLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(fHigh) + carry;
                fHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                bLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                bHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(fHigh, -14), bitshift(fLow, 18)), ...
                    bitor(bitshift(fHigh, -18), bitshift(fLow, 14))), ...
                    bitor(bitshift(fLow, -9), bitshift(fHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(fLow, -14), bitshift(fHigh, 18)), ...
                    bitor(bitshift(fLow, -18), bitshift(fHigh, 14))), ...
