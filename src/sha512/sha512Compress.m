                    bitor(bitshift(eHigh, -14), bitshift(eLow, 18)), ...
                    bitor(bitshift(eHigh, -18), bitshift(eLow, 14))), ...
                    bitor(bitshift(eLow, -9), bitshift(eHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(eLow, -14), bitshift(eHigh, 18)), ...
                    bitor(bitshift(eLow, -18), bitshift(eHigh, 14))), ...
                    bitor(bitshift(eHigh, -9), bitshift(eLow, 23)));
                choiceHigh = bitxor(gHigh, bitand(eHigh, bitxor(fHigh, gHigh)));
                temporaryHigh = double(hHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex) + double(wordsHigh(roundIndex, blockIndex));
                choiceLow = bitxor(gLow, bitand(eLow, bitxor(fLow, gLow)));
                temporaryLow = double(hLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex) + double(wordsLow(roundIndex, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(aHigh, -28), bitshift(aLow, 4)), ...
                    bitor(bitshift(aLow, -2), bitshift(aHigh, 30))), ...
                    bitor(bitshift(aLow, -7), bitshift(aHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(aLow, -28), bitshift(aHigh, 4)), ...
                    bitor(bitshift(aHigh, -2), bitshift(aLow, 30))), ...
                    bitor(bitshift(aHigh, -7), bitshift(aLow, 25)));
                majorityHigh = bitxor(bitand(aHigh, bHigh), ...
                    bitand(cHigh, bitxor(aHigh, bHigh)));
                majorityLow = bitxor(bitand(aLow, bLow), ...
                    bitand(cLow, bitxor(aLow, bLow)));
                sumLow = temporaryLow + double(dLow);
                carry = fix(sumLow * 2^-32);
                dLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(dHigh) + carry;
                dHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                hLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                hHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(dHigh, -14), bitshift(dLow, 18)), ...
                    bitor(bitshift(dHigh, -18), bitshift(dLow, 14))), ...
                    bitor(bitshift(dLow, -9), bitshift(dHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(dLow, -14), bitshift(dHigh, 18)), ...
                    bitor(bitshift(dLow, -18), bitshift(dHigh, 14))), ...
                    bitor(bitshift(dHigh, -9), bitshift(dLow, 23)));
                choiceHigh = bitxor(fHigh, bitand(dHigh, bitxor(eHigh, fHigh)));
                temporaryHigh = double(gHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex + 1) + double(wordsHigh(roundIndex + 1, blockIndex));
                choiceLow = bitxor(fLow, bitand(dLow, bitxor(eLow, fLow)));
                temporaryLow = double(gLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex + 1) + double(wordsLow(roundIndex + 1, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(hHigh, -28), bitshift(hLow, 4)), ...
                    bitor(bitshift(hLow, -2), bitshift(hHigh, 30))), ...
                    bitor(bitshift(hLow, -7), bitshift(hHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(hLow, -28), bitshift(hHigh, 4)), ...
                    bitor(bitshift(hHigh, -2), bitshift(hLow, 30))), ...
                    bitor(bitshift(hHigh, -7), bitshift(hLow, 25)));
                majorityHigh = bitxor(bitand(hHigh, aHigh), ...
                    bitand(bHigh, bitxor(hHigh, aHigh)));
                majorityLow = bitxor(bitand(hLow, aLow), ...
                    bitand(bLow, bitxor(hLow, aLow)));
                sumLow = temporaryLow + double(cLow);
                carry = fix(sumLow * 2^-32);
                cLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(cHigh) + carry;
                cHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                gLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                gHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(cHigh, -14), bitshift(cLow, 18)), ...
                    bitor(bitshift(cHigh, -18), bitshift(cLow, 14))), ...
                    bitor(bitshift(cLow, -9), bitshift(cHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(cLow, -14), bitshift(cHigh, 18)), ...
                    bitor(bitshift(cLow, -18), bitshift(cHigh, 14))), ...
                    bitor(bitshift(cHigh, -9), bitshift(cLow, 23)));
                choiceHigh = bitxor(eHigh, bitand(cHigh, bitxor(dHigh, eHigh)));
                temporaryHigh = double(fHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex + 2) + double(wordsHigh(roundIndex + 2, blockIndex));
                choiceLow = bitxor(eLow, bitand(cLow, bitxor(dLow, eLow)));
                temporaryLow = double(fLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex + 2) + double(wordsLow(roundIndex + 2, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(gHigh, -28), bitshift(gLow, 4)), ...
                    bitor(bitshift(gLow, -2), bitshift(gHigh, 30))), ...
                    bitor(bitshift(gLow, -7), bitshift(gHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(gLow, -28), bitshift(gHigh, 4)), ...
                    bitor(bitshift(gHigh, -2), bitshift(gLow, 30))), ...
                    bitor(bitshift(gHigh, -7), bitshift(gLow, 25)));
                majorityHigh = bitxor(bitand(gHigh, hHigh), ...
                    bitand(aHigh, bitxor(gHigh, hHigh)));
                majorityLow = bitxor(bitand(gLow, hLow), ...
                    bitand(aLow, bitxor(gLow, hLow)));
                sumLow = temporaryLow + double(bLow);
                carry = fix(sumLow * 2^-32);
                bLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(bHigh) + carry;
                bHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                fLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                fHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(bHigh, -14), bitshift(bLow, 18)), ...
                    bitor(bitshift(bHigh, -18), bitshift(bLow, 14))), ...
                    bitor(bitshift(bLow, -9), bitshift(bHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(bLow, -14), bitshift(bHigh, 18)), ...
                    bitor(bitshift(bLow, -18), bitshift(bHigh, 14))), ...
                    bitor(bitshift(bHigh, -9), bitshift(bLow, 23)));
                choiceHigh = bitxor(dHigh, bitand(bHigh, bitxor(cHigh, dHigh)));
                temporaryHigh = double(eHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex + 3) + double(wordsHigh(roundIndex + 3, blockIndex));
                choiceLow = bitxor(dLow, bitand(bLow, bitxor(cLow, dLow)));
                temporaryLow = double(eLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex + 3) + double(wordsLow(roundIndex + 3, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(fHigh, -28), bitshift(fLow, 4)), ...
                    bitor(bitshift(fLow, -2), bitshift(fHigh, 30))), ...
                    bitor(bitshift(fLow, -7), bitshift(fHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(fLow, -28), bitshift(fHigh, 4)), ...
                    bitor(bitshift(fHigh, -2), bitshift(fLow, 30))), ...
                    bitor(bitshift(fHigh, -7), bitshift(fLow, 25)));
                majorityHigh = bitxor(bitand(fHigh, gHigh), ...
                    bitand(hHigh, bitxor(fHigh, gHigh)));
                majorityLow = bitxor(bitand(fLow, gLow), ...
                    bitand(hLow, bitxor(fLow, gLow)));
                sumLow = temporaryLow + double(aLow);
                carry = fix(sumLow * 2^-32);
                aLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(aHigh) + carry;
                aHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                eLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                eHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(aHigh, -14), bitshift(aLow, 18)), ...
                    bitor(bitshift(aHigh, -18), bitshift(aLow, 14))), ...
                    bitor(bitshift(aLow, -9), bitshift(aHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(aLow, -14), bitshift(aHigh, 18)), ...
                    bitor(bitshift(aLow, -18), bitshift(aHigh, 14))), ...
                    bitor(bitshift(aHigh, -9), bitshift(aLow, 23)));
                choiceHigh = bitxor(cHigh, bitand(aHigh, bitxor(bHigh, cHigh)));
                temporaryHigh = double(dHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex + 4) + double(wordsHigh(roundIndex + 4, blockIndex));
                choiceLow = bitxor(cLow, bitand(aLow, bitxor(bLow, cLow)));
                temporaryLow = double(dLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex + 4) + double(wordsLow(roundIndex + 4, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(eHigh, -28), bitshift(eLow, 4)), ...
                    bitor(bitshift(eLow, -2), bitshift(eHigh, 30))), ...
                    bitor(bitshift(eLow, -7), bitshift(eHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(eLow, -28), bitshift(eHigh, 4)), ...
                    bitor(bitshift(eHigh, -2), bitshift(eLow, 30))), ...
                    bitor(bitshift(eHigh, -7), bitshift(eLow, 25)));
                majorityHigh = bitxor(bitand(eHigh, fHigh), ...
                    bitand(gHigh, bitxor(eHigh, fHigh)));
                majorityLow = bitxor(bitand(eLow, fLow), ...
                    bitand(gLow, bitxor(eLow, fLow)));
                sumLow = temporaryLow + double(hLow);
                carry = fix(sumLow * 2^-32);
                hLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(hHigh) + carry;
                hHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));
                sumLow = temporaryLow + double(sigma0Low) + double(majorityLow);
                carry = fix(sumLow * 2^-32);
                dLow = uint32(sumLow - 4294967296 * carry);
                sumValue = temporaryHigh + double(sigma0High) + double(majorityHigh) + carry;
                dHigh = uint32(sumValue - 4294967296 * fix(sumValue * 2^-32));

                sigma1High = bitxor(bitxor( ...
                    bitor(bitshift(hHigh, -14), bitshift(hLow, 18)), ...
                    bitor(bitshift(hHigh, -18), bitshift(hLow, 14))), ...
                    bitor(bitshift(hLow, -9), bitshift(hHigh, 23)));
                sigma1Low = bitxor(bitxor( ...
                    bitor(bitshift(hLow, -14), bitshift(hHigh, 18)), ...
                    bitor(bitshift(hLow, -18), bitshift(hHigh, 14))), ...
                    bitor(bitshift(hHigh, -9), bitshift(hLow, 23)));
                choiceHigh = bitxor(bHigh, bitand(hHigh, bitxor(aHigh, bHigh)));
                temporaryHigh = double(cHigh) + double(sigma1High) + ...
                    double(choiceHigh) + constantHigh(roundIndex + 5) + double(wordsHigh(roundIndex + 5, blockIndex));
                choiceLow = bitxor(bLow, bitand(hLow, bitxor(aLow, bLow)));
                temporaryLow = double(cLow) + double(sigma1Low) + ...
                    double(choiceLow) + constantLow(roundIndex + 5) + double(wordsLow(roundIndex + 5, blockIndex));
                sigma0High = bitxor(bitxor( ...
                    bitor(bitshift(dHigh, -28), bitshift(dLow, 4)), ...
                    bitor(bitshift(dLow, -2), bitshift(dHigh, 30))), ...
                    bitor(bitshift(dLow, -7), bitshift(dHigh, 25)));
                sigma0Low = bitxor(bitxor( ...
                    bitor(bitshift(dLow, -28), bitshift(dHigh, 4)), ...
                    bitor(bitshift(dHigh, -2), bitshift(dLow, 30))), ...
                    bitor(bitshift(dHigh, -7), bitshift(dLow, 25)));
                majorityHigh = bitxor(bitand(dHigh, eHigh), ...
                    bitand(fHigh, bitxor(dHigh, eHigh)));
                majorityLow = bitxor(bitand(dLow, eLow), ...
                    bitand(fLow, bitxor(dLow, eLow)));
                sumLow = temporaryLow + double(gLow);
                carry = fix(sumLow * 2^-32);
                gLow = uint32(sumLow - 4294967296 * carry);
