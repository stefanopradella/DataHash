            '84c87814a1f0ab72'; '8cc702081a6439ec'; ...
            '90befffa23631e28'; 'a4506cebde82bde9'; ...
            'bef9a3f7b2c67915'; 'c67178f2e372532b'; ...
            'ca273eceea26619c'; 'd186b8c721c0c207'; ...
            'eada7dd6cde0eb1e'; 'f57d4f7fee6ed178'; ...
            '06f067aa72176fba'; '0a637dc5a2c898a6'; ...
            '113f9804bef90dae'; '1b710b35131c471b'; ...
            '28db77f523047d84'; '32caab7b40c72493'; ...
            '3c9ebe0a15c9bebc'; '431d67c49c100d4c'; ...
            '4cc5d4becb3e42b6'; '597f299cfc657e2a'; ...
            '5fcb6fab3ad6faec'; '6c44198c4a475817'];
        constants = bitor(bitshift(uint64(hex2dec( ...
            constantHex(:, 1:8))), 32), ...
            uint64(hex2dec(constantHex(:, 9:16))));
    end

    highWords = uint64(16777216 * double(blocks(1:8:end, :)) + ...
        65536 * double(blocks(2:8:end, :)) + ...
        256 * double(blocks(3:8:end, :)) + ...
        double(blocks(4:8:end, :)));
    lowWords = uint64(16777216 * double(blocks(5:8:end, :)) + ...
        65536 * double(blocks(6:8:end, :)) + ...
        256 * double(blocks(7:8:end, :)) + ...
        double(blocks(8:8:end, :)));
    messageWords = bitor(bitshift(highWords, 32), lowWords);

    for blockIndex = 1:size(messageWords, 2)
        words = zeros(80, 1, 'uint64');
        words(1:16) = messageWords(:, blockIndex);
        for wordIndex = 17:80
            previous = words(wordIndex - 15);
            sigma0 = bitxor(bitxor( ...
                bitor(bitshift(previous, -1), bitshift(previous, 63)), ...
                bitor(bitshift(previous, -8), bitshift(previous, 56))), ...
                bitshift(previous, -7));
            previous = words(wordIndex - 2);
            sigma1 = bitxor(bitxor( ...
                bitor(bitshift(previous, -19), bitshift(previous, 45)), ...
                bitor(bitshift(previous, -61), bitshift(previous, 3))), ...
                bitshift(previous, -6));
            words(wordIndex) = add64Four(words(wordIndex - 16), sigma0, ...
                words(wordIndex - 7), sigma1);
        end

        a = state(1);
        b = state(2);
        c = state(3);
        d = state(4);
        e = state(5);
        f = state(6);
        g = state(7);
        h = state(8);

        for roundIndex = 1:80
            sigma1 = bitxor(bitxor( ...
                bitor(bitshift(e, -14), bitshift(e, 50)), ...
                bitor(bitshift(e, -18), bitshift(e, 46))), ...
                bitor(bitshift(e, -41), bitshift(e, 23)));
            choice = bitxor(g, bitand(e, bitxor(f, g)));
            temporary1 = add64Five(h, sigma1, choice, ...
                constants(roundIndex), words(roundIndex));

            sigma0 = bitxor(bitxor( ...
                bitor(bitshift(a, -28), bitshift(a, 36)), ...
                bitor(bitshift(a, -34), bitshift(a, 30))), ...
                bitor(bitshift(a, -39), bitshift(a, 25)));
            majority = bitxor(bitand(a, b), bitand(c, bitxor(a, b)));
            temporary2 = add64Two(sigma0, majority);

            h = g;
            g = f;
            f = e;
            e = add64Two(d, temporary1);
            d = c;
            c = b;
            b = a;
            a = add64Two(temporary1, temporary2);
        end

        workingState = [a; b; c; d; e; f; g; h];
        for wordIndex = 1:8
            state(wordIndex) = add64Two(state(wordIndex), ...
                workingState(wordIndex));
        end
    end
end

function value = add64Two(first, second)
    wordMask = uint64(4294967295);
    lowSum = bitand(first, wordMask) + bitand(second, wordMask);
    highSum = bitshift(first, -32) + bitshift(second, -32) + ...
        bitshift(lowSum, -32);
    value = bitor(bitshift(bitand(highSum, wordMask), 32), ...
        bitand(lowSum, wordMask));
end

function value = add64Four(first, second, third, fourth)
    wordMask = uint64(4294967295);
    lowSum = bitand(first, wordMask) + bitand(second, wordMask) + ...
        bitand(third, wordMask) + bitand(fourth, wordMask);
    highSum = bitshift(first, -32) + bitshift(second, -32) + ...
        bitshift(third, -32) + bitshift(fourth, -32) + ...
        bitshift(lowSum, -32);
    value = bitor(bitshift(bitand(highSum, wordMask), 32), ...
        bitand(lowSum, wordMask));
end

function value = add64Five(first, second, third, fourth, fifth)
    wordMask = uint64(4294967295);
    lowSum = bitand(first, wordMask) + bitand(second, wordMask) + ...
        bitand(third, wordMask) + bitand(fourth, wordMask) + ...
        bitand(fifth, wordMask);
    highSum = bitshift(first, -32) + bitshift(second, -32) + ...
        bitshift(third, -32) + bitshift(fourth, -32) + ...
        bitshift(fifth, -32) + bitshift(lowSum, -32);
    value = bitor(bitshift(bitand(highSum, wordMask), 32), ...
        bitand(lowSum, wordMask));
end
